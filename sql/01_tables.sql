CREATE TABLE app_user (
    user_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    username VARCHAR2(40) NOT NULL UNIQUE,
    password_hash VARCHAR2(64) NOT NULL,
    password_salt VARCHAR2(32) NOT NULL,
    role_name VARCHAR2(20) NOT NULL CHECK (role_name IN ('ADMIN','DOCTOR','RECEPTIONIST','PHARMACIST','LAB_TECH')),
    failed_attempts NUMBER DEFAULT 0 NOT NULL,
    locked_flag CHAR(1) DEFAULT 'N' CHECK (locked_flag IN ('Y','N')),
    active_flag CHAR(1) DEFAULT 'Y' CHECK (active_flag IN ('Y','N'))
);
CREATE TABLE department (
    department_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    department_name VARCHAR2(80) NOT NULL UNIQUE,
    description VARCHAR2(250)
);
CREATE TABLE doctor (
    doctor_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    department_id NUMBER REFERENCES department(department_id),
    full_name VARCHAR2(100) NOT NULL,
    specialization VARCHAR2(100) NOT NULL,
    qualification VARCHAR2(100),
    consultation_fee NUMBER(10,2) DEFAULT 0 CHECK (consultation_fee >= 0),
    active_flag CHAR(1) DEFAULT 'Y' CHECK (active_flag IN ('Y','N'))
);
CREATE TABLE patient (
    patient_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    patient_code VARCHAR2(20) UNIQUE,
    full_name VARCHAR2(100) NOT NULL,
    phone VARCHAR2(10) NOT NULL,
    dob DATE,
    gender VARCHAR2(12) DEFAULT 'Other',
    blood_group VARCHAR2(3),
    allergies VARCHAR2(500),
    emergency_contact VARCHAR2(10),
    active_flag CHAR(1) DEFAULT 'Y' CHECK (active_flag IN ('Y','N')),
    created_at DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT ck_patient_phone CHECK (REGEXP_LIKE(phone, '^[0-9]{10}$'))
);
CREATE TABLE appointment (
    appointment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    patient_id NUMBER NOT NULL REFERENCES patient(patient_id),
    doctor_id NUMBER NOT NULL REFERENCES doctor(doctor_id),
    appointment_date TIMESTAMP NOT NULL,
    reason VARCHAR2(300),
    status VARCHAR2(20) DEFAULT 'BOOKED' CHECK (status IN ('BOOKED','CHECKED_IN','COMPLETED','CANCELLED','NO_SHOW')),
    created_at DATE DEFAULT SYSDATE NOT NULL
);
CREATE TABLE ward (
    ward_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ward_name VARCHAR2(50) NOT NULL UNIQUE,
    daily_charge NUMBER(10,2) NOT NULL CHECK (daily_charge >= 0)
);
CREATE TABLE bed (
    bed_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ward_id NUMBER NOT NULL REFERENCES ward(ward_id),
    bed_code VARCHAR2(20) NOT NULL UNIQUE,
    status VARCHAR2(15) DEFAULT 'FREE' CHECK (status IN ('FREE','OCCUPIED','MAINTENANCE'))
);
CREATE TABLE admission (
    admission_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    patient_id NUMBER NOT NULL REFERENCES patient(patient_id),
    bed_id NUMBER NOT NULL REFERENCES bed(bed_id),
    admit_date DATE DEFAULT SYSDATE NOT NULL,
    discharge_date DATE,
    status VARCHAR2(15) DEFAULT 'ADMITTED' CHECK (status IN ('ADMITTED','DISCHARGED'))
);
CREATE TABLE medicine (
    medicine_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    medicine_name VARCHAR2(100) NOT NULL UNIQUE,
    category VARCHAR2(60),
    unit_price NUMBER(10,2) NOT NULL CHECK (unit_price >= 0),
    stock_qty NUMBER DEFAULT 0 NOT NULL CHECK (stock_qty >= 0),
    reorder_level NUMBER DEFAULT 10 NOT NULL CHECK (reorder_level >= 0),
    expiry_date DATE
);
CREATE TABLE lab_order (
    lab_order_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    patient_id NUMBER NOT NULL REFERENCES patient(patient_id),
    test_name VARCHAR2(100) NOT NULL,
    order_date DATE DEFAULT SYSDATE NOT NULL,
    status VARCHAR2(20) DEFAULT 'ORDERED' CHECK (status IN ('ORDERED','SAMPLE_COLLECTED','RESULT_READY')),
    result_value VARCHAR2(100),
    normal_range VARCHAR2(100),
    abnormal_flag CHAR(1) DEFAULT 'N' CHECK (abnormal_flag IN ('Y','N')),
    price NUMBER(10,2) DEFAULT 0 CHECK (price >= 0)
);
CREATE TABLE bill (
    bill_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    bill_number VARCHAR2(30) UNIQUE,
    patient_id NUMBER NOT NULL REFERENCES patient(patient_id),
    appointment_id NUMBER REFERENCES appointment(appointment_id),
    admission_id NUMBER REFERENCES admission(admission_id),
    bill_date DATE DEFAULT SYSDATE NOT NULL,
    subtotal NUMBER(12,2) DEFAULT 0 NOT NULL,
    discount_amount NUMBER(12,2) DEFAULT 0 NOT NULL,
    tax_amount NUMBER(12,2) DEFAULT 0 NOT NULL,
    total_amount NUMBER(12,2) DEFAULT 0 NOT NULL,
    paid_amount NUMBER(12,2) DEFAULT 0 NOT NULL,
    status VARCHAR2(15) DEFAULT 'UNPAID' CHECK (status IN ('UNPAID','PARTIAL','PAID'))
);
CREATE TABLE bill_item (
    bill_item_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    bill_id NUMBER NOT NULL REFERENCES bill(bill_id) ON DELETE CASCADE,
    item_type VARCHAR2(30) NOT NULL,
    description VARCHAR2(200) NOT NULL,
    quantity NUMBER(10,2) DEFAULT 1 NOT NULL,
    unit_price NUMBER(10,2) NOT NULL,
    line_total NUMBER(12,2) NOT NULL
);
CREATE TABLE payment (
    payment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    bill_id NUMBER NOT NULL REFERENCES bill(bill_id),
    payment_date DATE DEFAULT SYSDATE NOT NULL,
    amount NUMBER(12,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR2(10) NOT NULL CHECK (payment_method IN ('CASH','CARD','UPI')),
    reference_note VARCHAR2(100)
);
CREATE TABLE audit_log (
    audit_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    event_time TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    db_user VARCHAR2(128),
    app_user VARCHAR2(40),
    table_name VARCHAR2(50),
    action_name VARCHAR2(10),
    record_key VARCHAR2(100),
    details VARCHAR2(1000)
);
